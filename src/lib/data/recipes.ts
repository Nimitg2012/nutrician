function n(ids: string[]): Recipe["ingredients"] {
  return ids.map((id) => {
    const food = FOOD_BY_ID[id];
    return { foodId: id, name: food?.name ?? id, quantity: food?.servingSize ?? "1 serving" };
  });
}

