export const RECIPE_BY_ID = Object.fromEntries(RECIPES.map((recipe) => [recipe.id, recipe])) as Record<string, Recipe>;

export function recipeNutrients(recipe: Recipe) {
  return nutrients({
    calories: recipe.calories,
    protein: recipe.protein,
    carbs: recipe.carbs,
    fat: recipe.fat,
    fiber: recipe.fiber,
  });
}

export function recipeFromFood(foodId: string): Recipe | undefined {
  const food = FOOD_BY_ID[foodId];
  if (!food) return undefined;
  return RECIPES.find((recipe) => recipe.id === foodId || recipe.name === food.name);
}

